//! Minimal-but-valid OOXML part sets used by [`crate::create_empty_package`] to
//! produce blank documents. Each set contains just enough parts for
//! Word/Excel/PowerPoint to open the package as an empty document, and omits
//! `docProps` so no author/timestamp metadata is baked in.
//!
//! The XML is the canonical minimal structure. After editing, regenerate the
//! packages (call [`crate::create_empty_package`] in a test) and spot-check a
//! produced file in the corresponding Office app.

/// A part's path inside the package (ZIP entry name, forward slashes) paired
/// with its XML content.
pub(crate) type Part = (&'static str, &'static str);

/// Blank `.docx`: one empty paragraph, no section properties (Word supplies
